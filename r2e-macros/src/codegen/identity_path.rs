//! The façade-binding emitter shared by every transport that runs members on
//! a `#[controller]` struct: HTTP handlers (`codegen/handlers.rs`) and MCP
//! members (`mcp_codegen/tool_impl.rs`).
//!
//! Both bind the same thing — the `#[controller]`-generated
//! `__R2eRequestData_<Name>` turned into the per-request façade by
//! `__r2e_meta_<Name>::bind_request(core, data)`, then `__ctrl = &__facade` —
//! and differ only in where the request data comes from ([`Arrival`]):
//!
//! - HTTP extracts it here, from `__parts` against `__state`
//!   ([`Arrival::ExtractHere`]);
//! - MCP finds it deposited in the call parts' extensions by the endpoint
//!   layer, or builds it by hand for a service without request scope
//!   ([`Arrival::FromDeposit`]).
//!
//! The guard identity expression ([`guard_identity`]) is shared the same way:
//! a parameter identity wins, an `#[anonymous]` HTTP route has none, and
//! otherwise the identity is read off the façade through
//! `__r2e_meta_<Name>::guard_identity`.
//!
//! An HTTP `#[anonymous]` route never binds a façade: it runs on the core
//! ([`bind_core`]). MCP members always run on the façade.

use proc_macro2::{Ident, TokenStream};
use quote::quote;

/// Where a member's request-scoped data comes from.
pub(crate) enum Arrival<'a> {
    /// HTTP: extracted here through `RequestData<__R2eS>` from `__parts` and
    /// `__state`; a rejection (bound as `__rej`) runs `on_reject`.
    ExtractHere {
        krate: &'a TokenStream,
        on_reject: TokenStream,
    },
    /// MCP: `unscoped_request_data` when the controller has no request scope,
    /// otherwise the data deposited in `__call.parts` by the endpoint layer;
    /// missing data is an `McpError::Internal(missing)`.
    FromDeposit {
        mcp: &'a TokenStream,
        missing: String,
    },
}

/// The names the binding refers to (all generated by `#[controller]`).
pub(crate) struct FacadeNames<'a> {
    /// `__r2e_meta_<Name>`.
    pub meta_mod: &'a Ident,
    /// `__R2eRequestData_<Name>`.
    pub data_name: &'a Ident,
    /// The request-data marker generic (`__R2eMd`).
    pub data_marker: &'a Ident,
}

/// Bind `__data`, then `__facade = bind_request(core, __data)` and
/// `__ctrl = &__facade`.
pub(crate) fn bind_facade(
    names: &FacadeNames<'_>,
    core: TokenStream,
    arrival: Arrival<'_>,
) -> TokenStream {
    let FacadeNames {
        meta_mod,
        data_name,
        data_marker,
    } = names;
    let data = match arrival {
        Arrival::ExtractHere { krate, on_reject } => quote! {
            let __data = match <#data_name<#data_marker> as #krate::web::extract::RequestData<__R2eS>>
                ::extract(&mut __parts, &__state).await
            {
                Ok(__d) => __d,
                Err(__rej) => #on_reject
            };
        },
        Arrival::FromDeposit { mcp, missing } => quote! {
            let __data: #data_name<#data_marker> =
                match #meta_mod::unscoped_request_data::<#data_marker>() {
                    ::core::option::Option::Some(__d) => __d,
                    ::core::option::Option::None => {
                        match #mcp::__macro_support::request_data::<#data_name<#data_marker>>(
                            __call.parts.as_deref(),
                        ) {
                            ::core::option::Option::Some(__d) => __d,
                            ::core::option::Option::None => {
                                return ::core::result::Result::Err(
                                    #mcp::__macro_support::McpError::Internal(
                                        ::std::string::String::from(#missing),
                                    ),
                                );
                            }
                        }
                    }
                };
        },
    };
    quote! {
        #data
        let __facade = #meta_mod::bind_request(#core, __data);
        let __ctrl = &__facade;
    }
}

/// Borrow the core as the receiver (`__ctrl: &Core`) — HTTP `#[anonymous]`
/// routes, which extract no request scope.
pub(crate) fn bind_core(controller_name: &Ident, core: TokenStream) -> TokenStream {
    quote! {
        let __ctrl: &#controller_name = &#core;
    }
}

/// Which identity a guard context carries.
pub(crate) enum GuardIdentity<'a> {
    /// A parameter-level `#[inject(identity)]`, already bound to `binding`.
    Param { binding: &'a Ident, optional: bool },
    /// `#[anonymous]`: no identity was extracted; `None` typed to the
    /// controller's `IdentityType` keeps `GuardContext<I>` pinned.
    Anonymous,
    /// The struct-level identity (or none), read off the façade.
    Facade,
}

/// The identity expression of a guard context.
pub(crate) fn guard_identity(meta_mod: &Ident, source: GuardIdentity<'_>) -> TokenStream {
    match source {
        GuardIdentity::Param {
            binding,
            optional: true,
        } => quote! { #binding.as_ref() },
        GuardIdentity::Param {
            binding,
            optional: false,
        } => quote! { ::core::option::Option::Some(&#binding) },
        GuardIdentity::Anonymous => {
            quote! { ::core::option::Option::<&#meta_mod::IdentityType>::None }
        }
        GuardIdentity::Facade => quote! { #meta_mod::guard_identity(__ctrl) },
    }
}
