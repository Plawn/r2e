#!/usr/bin/env bash
#
# smoke-registry.sh — build what a user builds: a throwaway application that
# depends on the facade from crates.io alone.
#
# The workspace is always built from source, so a crate that a release left
# behind on crates.io is invisible to every other check: r2e-core 0.7.0 shipped
# while r2e-macros stayed at 0.6.0, and every registry build of r2e 0.7/0.8
# failed on `#[routes]` (E0614) and `#[mcp_routes]` (missing field `meta`)
# although `cargo test --workspace` was green (#1092). This script scaffolds a
# minimal app in a temporary directory outside the workspace — a validated
# `#[routes]` handler and an `#[mcp_routes]` tool on the `App` trait — and
# `cargo check`s it with no `[patch]` and no path dependency. release.yml runs
# it after publishing; run it by hand to reproduce a registry-only failure.
#
# Usage:
#   scripts/smoke-registry.sh [VERSION]   # r2e = "=VERSION" from crates.io
#                                         # (default: the facade version of this tree)
#   scripts/smoke-registry.sh --patch     # same app, every workspace crate patched to
#                                         # this tree: checks the snippet (and the tree)
#                                         # before the release exists
#
# Environment:
#   SMOKE_TOOLCHAIN   `cargo +<toolchain>` (release.yml passes `stable`; default: the
#                     toolchain cargo resolves outside the repo, i.e. not the
#                     rust-toolchain.toml nightly)
#   SMOKE_DIR         where to scaffold (kept afterwards; default: a mktemp dir,
#                     removed on success, kept and named on failure)
#
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
ROOT=$(pwd)

die() { printf '\033[31merror: %s\033[0m\n' "$*" >&2; exit 1; }

PATCH=0
VERSION=""
for arg in "$@"; do
    case "$arg" in
        --patch) PATCH=1 ;;
        -h|--help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        -*) die "unknown flag $arg" ;;
        *) VERSION="$arg" ;;
    esac
done
[[ -n "$VERSION" ]] || VERSION=$(python3 scripts/versions.py version r2e)

# The crates the snippet names next to `r2e`, at the requirements the workspace
# pins: `garde::Validate` and `schemars::JsonSchema` must be the same traits
# r2e-core compiles against, or the derive silently stops meaning anything.
dep_req() {
    python3 - "$1" <<'PY'
import re, sys
name = sys.argv[1]
text = open("Cargo.toml", encoding="utf-8").read()
m = re.search(r'(?m)^' + re.escape(name) + r'\s*=\s*(?:"([^"]+)"|\{[^}\n]*\bversion\s*=\s*"([^"]+)")', text)
if not m:
    sys.exit(f"{name}: no [workspace.dependencies] entry")
print(m.group(1) or m.group(2))
PY
}
SERDE_REQ=$(dep_req serde)
SCHEMARS_REQ=$(dep_req schemars)
GARDE_REQ=$(dep_req garde)

keep_dir=1
if [[ -z "${SMOKE_DIR:-}" ]]; then
    # An explicit template: GNU mktemp rejects `-t prefix` (BSD/macOS only).
    SMOKE_DIR=$(mktemp -d "${TMPDIR:-/tmp}/r2e-smoke.XXXXXX")
    keep_dir=0
fi
mkdir -p "$SMOKE_DIR/src"
case "$SMOKE_DIR" in
    "$ROOT"/*) die "SMOKE_DIR must be outside the workspace ($SMOKE_DIR)" ;;
esac

patch_block=""
if [[ $PATCH -eq 1 ]]; then
    # Every publishable crate, so the transitive r2e-* requirements of a
    # not-yet-published facade resolve to the tree too. Unused entries only warn.
    patch_block=$(python3 - <<'PY'
import json, os, subprocess
meta = json.loads(subprocess.check_output(["cargo", "metadata", "--no-deps", "--format-version", "1"]))
print("[patch.crates-io]")
for p in sorted(meta["packages"], key=lambda p: p["name"]):
    if p.get("publish") == []:
        continue
    print(f'{p["name"]} = {{ path = "{os.path.dirname(p["manifest_path"])}" }}')
PY
)
fi

cat > "$SMOKE_DIR/Cargo.toml" <<EOF
# Generated by scripts/smoke-registry.sh — a user's Cargo.toml, nothing more.
[package]
name = "r2e-smoke"
version = "0.0.0"
edition = "2024"
publish = false

# Detached from any enclosing workspace.
[workspace]

[dependencies]
r2e = { version = "=${VERSION}", features = ["mcp"] }
serde = { version = "${SERDE_REQ}", features = ["derive"] }
schemars = "${SCHEMARS_REQ}"
garde = { version = "${GARDE_REQ}", features = ["derive"] }

${patch_block}
EOF

# The two code paths #1092 broke, on the canonical App-trait layout (llm/quick-start.md).
cat > "$SMOKE_DIR/src/app.rs" <<'EOF'
use garde::Validate;
use r2e::prelude::*;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Deserialize, Validate, JsonSchema)]
pub struct CreateUserRequest {
    #[garde(length(min = 1, max = 100))]
    pub name: String,
    #[garde(email)]
    pub email: String,
}

#[derive(Serialize, JsonSchema)]
pub struct User {
    pub name: String,
    pub email: String,
}

#[controller(path = "/users")]
pub struct UserController;

#[routes]
impl UserController {
    // `Json<T: Validate>` auto-validates: the generated handler calls
    // `__maybe_validate` — the call site a stale r2e-macros broke (E0614).
    #[post("/")]
    async fn create(&self, Json(body): Json<CreateUserRequest>) -> Json<User> {
        Json(User { name: body.name, email: body.email })
    }
}

#[derive(Deserialize, JsonSchema, ObjectParams)]
pub struct AddIn {
    pub a: f64,
    pub b: f64,
}

#[derive(Serialize, JsonSchema)]
pub struct AddOut {
    pub value: f64,
}

#[controller]
pub struct MathTools;

#[mcp_routes]
impl MathTools {
    /// Add two numbers.
    // The generated `ToolRoute` literal names every field of the r2e-mcp
    // release it is paired with (`meta` since 0.7.0).
    #[tool(read_only, idempotent)]
    async fn add(&self, Params(p): Params<AddIn>) -> Json<AddOut> {
        Json(AddOut { value: p.a + p.b })
    }
}

pub struct SmokeApp;

impl App for SmokeApp {
    type Env = ();

    async fn setup() -> Result<(), BootError> {
        Ok(())
    }

    async fn build(b: AppBuilder, _env: ()) -> Result<impl BootableApp, BootError> {
        Ok(b.load_config::<()>()
            .plugin(McpServer::new())
            .build_state()
            .await
            .register_controller::<UserController>()
            .register_mcp_service::<MathTools>())
    }
}
EOF

cat > "$SMOKE_DIR/src/main.rs" <<'EOF'
r2e::app_main!(SmokeApp);
EOF

cargo_cmd=(cargo)
[[ -n "${SMOKE_TOOLCHAIN:-}" ]] && cargo_cmd=(cargo "+${SMOKE_TOOLCHAIN}")

cd "$SMOKE_DIR"
printf '==> %s against %s in %s\n' "r2e = \"=${VERSION}\"" \
    "$([[ $PATCH -eq 1 ]] && echo "this tree ([patch.crates-io])" || echo crates.io)" "$SMOKE_DIR"

# Right after a publish the sparse index can lag by a minute or two; the
# resolution is what lags, so retry only that.
attempt=0
until "${cargo_cmd[@]}" generate-lockfile; do
    attempt=$((attempt + 1))
    [[ $attempt -lt 10 ]] || die "the registry does not resolve r2e ${VERSION} after $attempt attempts"
    printf 'resolution failed (index lag?) — retrying in 30s (%s/10)\n' "$attempt"
    sleep 30
done

printf '==> resolved r2e crates:\n'
"${cargo_cmd[@]}" metadata --format-version 1 > metadata.json
python3 - metadata.json <<'PY'
import json, sys
meta = json.load(open(sys.argv[1], encoding="utf-8"))
for p in sorted(meta["packages"], key=lambda p: p["name"]):
    if p["name"].startswith("r2e"):
        print(f"  {p['name']:22} {p['version']:8} {p['source'] or p['manifest_path']}")
PY

if "${cargo_cmd[@]}" check; then
    printf '\033[32mok — a registry-only app compiles against r2e %s\033[0m\n' "$VERSION"
    [[ $keep_dir -eq 1 ]] || rm -rf "$SMOKE_DIR"
else
    die "a registry-only app does not compile against r2e ${VERSION} — kept in $SMOKE_DIR"
fi
