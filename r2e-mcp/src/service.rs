//! The [`McpService`] trait — what `#[routes]` implements.

use std::sync::Arc;

use r2e_core::beans::BeanContext;
use r2e_core::config::{MissingKeyError, R2eConfig};

use crate::route::McpRoutes;

/// Trait for MCP tool services that can be registered with the R2E builder.
///
/// Implement this trait (typically via the `#[routes]` macro) to expose a
/// type's `#[tool]`/`#[resource]`/`#[prompt]` methods over the MCP
/// endpoint. The service core is constructed from the resolved bean graph by
/// type (see [`ContextConstruct`](r2e_core::ContextConstruct)) — once per
/// builder, at registration; each route's dispatch closure clones an `Arc`
/// of it per call.
///
/// # One core per type
///
/// A type whose `#[routes]` impl mixes HTTP routes and MCP members is both a
/// [`Controller`](r2e_core::Controller) and an `McpService`, and it has
/// exactly **one** runtime core: `register_mcp_service` and
/// `register_controller` take it from the builder's per-type core store
/// (whichever registers first constructs it, through its own `construct`),
/// so a tool sees the state a `#[post_construct]` hook wrote and calls a
/// `#[scheduled]` method through the interceptors `register_controller`
/// filled. Lifecycle and background members (`#[post_construct]`,
/// `#[on_start]`, `#[pre_destroy]`, `#[scheduled]`, `#[consumer]`,
/// `#[async_exec]`) are wired by `register_controller` only:
/// [`NEEDS_CONTROLLER_REGISTRATION`](Self::NEEDS_CONTROLLER_REGISTRATION)
/// lists them, and a type that declares any but is registered only with
/// `register_mcp_service` fails boot naming the missing
/// `.register_controller::<Type>()`.
///
/// Services accumulate into the
/// [`McpServiceRegistry`](crate::registry::McpServiceRegistry), which the
/// [`McpServer`](crate::McpServer) plugin drains once when the router is
/// assembled. Any number of services share the single MCP endpoint; tool
/// and prompt names and resource URIs must be globally unique (a duplicate
/// is a boot panic naming both services).
///
/// # State and witness generics
///
/// `T` is the application state type, `W` an opaque witness carrier — the
/// MCP peer of [`Controller<T, W>`](r2e_core::Controller). The generated impl
/// is generic over the state and parks one extraction marker per member that
/// declares an `#[inject(identity)]` parameter in `W`, so the identity goes
/// through the very same
/// [`FromRequestPartsVia`](r2e_core::web::extract::FromRequestPartsVia)
/// extractor as on an HTTP route — an app `FromRequestParts` type, a
/// bean-backed extractor (`AuthenticatedUser` with the `JwtClaimsValidator`
/// bean), or the `mcp.auth` principal ([`McpPrincipal`](crate::McpPrincipal),
/// marker [`ViaMcpAuth`](crate::ViaMcpAuth)). A
/// missing bean is a compile error at `register_mcp_service()`. User code
/// never names `T` or `W`: registration infers them.
///
/// # Example (generated by macro)
///
/// ```ignore
/// impl<__R2eS, __R2eMpWhoami> McpService<__R2eS, (__R2eMpWhoami,)> for MathTools
/// where
///     __R2eS: Clone + Send + Sync + 'static,
///     __R2eMpWhoami: Send + Sync + 'static,
///     AppUser: FromRequestPartsVia<__R2eS, __R2eMpWhoami>,
/// {
///     fn service_name() -> &'static str { "MathTools" }
///
///     fn construct(_state: &__R2eS, ctx: &BeanContext) -> Self {
///         <MathTools as ContextConstruct>::from_context(ctx)
///     }
///
///     fn routes(state: &__R2eS, core: Arc<Self>, ctx: &Arc<BeanContext>) -> McpRoutes {
///         let wrapper = Arc::new(__R2eMcpMathTools {
///             core, // the builder's one core for MathTools
///             // plus prebuilt interceptor/guard products when decorated
///         });
///         // the state is shared (one Arc) by the members that extract an
///         // identity from it
///         McpRoutes {
///             tools: vec![/* one ToolRoute per #[tool] method */],
///             resources: vec![/* … per #[resource] method */],
///             prompts: vec![/* … per #[prompt] method */],
///             uses_session: false, // true when a member takes `McpSession`
///         }
///     }
/// }
/// ```
pub trait McpService<T: Clone + Send + Sync + 'static, W = ()>: 'static {
    /// The service name (used in diagnostics and duplicate-tool errors).
    fn service_name() -> &'static str;

    /// Validate the config this service reads, in one aggregated report —
    /// the MCP peer of
    /// [`Controller::validate_config`](r2e_core::Controller::validate_config):
    /// the core's own `#[config]` keys plus every `#[intercept]`/`#[guard]`
    /// spec's declared keys. Called by `register_mcp_service`. The default
    /// reports nothing.
    fn validate_config(_config: &R2eConfig) -> Vec<MissingKeyError> {
        Vec::new()
    }

    /// The lifecycle/background markers this type's `#[routes]` impl
    /// declares (spelled `#[post_construct]`, `#[scheduled]`, …): members
    /// only `register_controller` wires. Non-empty only on a mixed impl;
    /// `register_mcp_service` records it, and the build fails with an
    /// actionable error when the type was never registered with
    /// `register_controller`. The default is empty.
    const NEEDS_CONTROLLER_REGISTRATION: &'static [&'static str] = &[];

    /// Build the service core from the resolved bean graph — the
    /// [`Controller::construct`](r2e_core::Controller::construct) peer.
    /// Called at most once per builder: registration takes the core from the
    /// builder's per-type store, so a type registered as both a controller
    /// and an MCP service shares one core.
    fn construct(state: &T, ctx: &BeanContext) -> Self
    where
        Self: Sized;

    /// Build this service's routes (tools, resources, prompts) around the
    /// builder's one `core` for this type — one wrapper, one set of prebuilt
    /// decorators, shared by every member's dispatch closure. `state` is the
    /// resolved application state, the second argument of every member's
    /// `#[inject(identity)]` extractor.
    fn routes(state: &T, core: Arc<Self>, ctx: &Arc<BeanContext>) -> McpRoutes
    where
        Self: Sized;
}
